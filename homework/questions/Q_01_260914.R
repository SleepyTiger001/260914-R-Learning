# ---- （1）题目背景 -----------------------------------------------------------

# 你已经学过：两个日期直接相减，就能算出中间隔了多少天 ——
#     end - start          # 结果形如 Time difference of 1839 days
# 但它只给“天”这一个单位。那想按周看是多少？按小时、按分钟、按秒又各是多少？
# R 早就备好了现成函数：difftime()。它的 units 参数决定“以什么单位计算”，
# 可选单位有："secs"（秒）、"mins"（分）、"hours"（小时）、"days"（天）、"weeks"（周）。
# 本次作业就做一件事：先把字符串日期转成日期型，再用 difftime() 把同一个间隔
# 换成五种单位，各算一遍。

# ---- （2）具体要求 -----------------------------------------------------------

# 要求 1
#   定义两个「字符串类型」的日期变量：
#       start_str <- "2021-09-01"
#       end_str   <- "2026-09-14"
#   用 class() 打印它们的类型，确认拿到的是 character。

# 要求 2
#   用 as.Date() 把这两个字符串转成日期型，分别存进 start 与 end；
#   再用 class() 确认它们已经变成 "Date"，并 print() 看看长什么样。

# 要求 3
#   用减号 `-` 计算两个日期相隔的天数，并用 as.numeric() 取出纯数字，打印在控制台。

# 要求 4
#   用 difftime() 计算 end 与 start 的间隔，units 参数依次取：
#       "secs"（秒）、"mins"（分）、"hours"（小时）、"days"（天）、"weeks"（周）
#   每个结果都用 as.numeric() 取出纯数字再打印。
