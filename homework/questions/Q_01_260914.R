# ---- 题目背景 ----------------------------------------------------------------
# 你认识某个人、或者开始做某件事，已经多久了？这个问题在 R 里就是"两个日期相减"。
# 但"相差多久"有四种问法：多少天、多少周、多少个月、多少年。前两种 Base R 直接算，
# 后两种没有现成函数，需要你自己定口径 —— 这正是本次作业的重点。


# ---- 具体要求 ----------------------------------------------------------------

# 要求 1（字符串 → 变量）
#   定义两个「字符串类型」的日期变量（注意：带引号，是字符不是日期）：
#       start_str = "2021-09-01"
#       end_str   = "2026-09-14"
#   并用 class() 打印它们的类型，确认拿到的是 character。

# 要求 2（字符串 → 日期型）
#   用 as.Date() 把上面两个字符串转成日期型，分别存进 start 与 end；
#   再用 class() 确认已经变成 "Date"，并 print() 看看它们长什么样。

# 要求 3（算四种差值）
#   （1）相差多少天：Base R 的日期相减即可，注意用 as.numeric() 取出纯数字；
#   （2）相差多少周：用 difftime(..., units = "weeks")，或用天数除以 7；
#        并额外给出「整周数 + 余几天」（提示：%/% 与 %%）；
#   （3）相差多少个月；（4）相差多少年。
#   ⚠ 年与月没有唯一答案，取决于口径，你必须：
#       · 至少实现一种口径；
#       · 在代码注释里写明你用的是哪一种，并说明为什么数值是小数 / 是整数。

# 要求 4（打印成人话）
#   用 cat() 或 print() 把结果打印出来，格式参考：
#       2021-09-01 到 2026-09-14 相差 5 年 0 月 13 天（合 1839 天 / 262 周 5 天）
#   注意：cat() 直接打印日期对象会输出"距 1970-01-01 的天数"（比如 18871），
#   想打出 2021-09-01 这种样子，得先 as.character() 或 format() 转一下。

